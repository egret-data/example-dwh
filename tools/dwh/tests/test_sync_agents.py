import pytest

from dwh.cli import main
from dwh.sync_agents import SkillError, load_skills, render, sync

SKILL = """---
name: dwh-demo
description: Use when demonstrating the generator
---

# dwh-demo

Body text.
"""


@pytest.fixture
def repo(tmp_path):
    (tmp_path / "AGENTS.md").write_text("# Agents\n\nRead the rules.\n")
    skill = tmp_path / "skills" / "dwh-demo"
    skill.mkdir(parents=True)
    (skill / "SKILL.md").write_text(SKILL)
    (skill / "checklist.md").write_text("- item\n")
    return tmp_path


def test_render_produces_every_tool_file(repo):
    out = render(repo)

    assert set(out) == {
        "CLAUDE.md",
        "GEMINI.md",
        ".claude/skills/dwh-demo/SKILL.md",
        ".claude/skills/dwh-demo/checklist.md",
        ".cursor/rules/dwh-demo.mdc",
        ".cursor/rules/agents.mdc",
        ".github/copilot-instructions.md",
    }
    assert out["CLAUDE.md"].endswith("@AGENTS.md\n")
    assert "Generated by `dwh sync-agents`" in out["CLAUDE.md"]
    claude_skill = out[".claude/skills/dwh-demo/SKILL.md"]
    assert claude_skill.startswith("---\nname: dwh-demo\n")  # frontmatter stays first
    assert "Generated by `dwh sync-agents`" in claude_skill
    assert out[".claude/skills/dwh-demo/checklist.md"] == "- item\n"
    mdc = out[".cursor/rules/dwh-demo.mdc"]
    assert 'description: "Use when demonstrating the generator"' in mdc
    assert "alwaysApply: false" in mdc
    assert "Body text." in mdc
    assert "alwaysApply: true" in out[".cursor/rules/agents.mdc"]
    copilot = out[".github/copilot-instructions.md"]
    assert "Read the rules." in copilot
    assert "`skills/dwh-demo/SKILL.md`: Use when demonstrating the generator" in copilot


def test_sync_writes_then_check_is_clean(repo):
    written = sync(repo, check=False)

    assert "CLAUDE.md" in written
    assert sync(repo, check=True) == []


def test_check_reports_hand_edits_and_stale_files(repo):
    sync(repo, check=False)
    (repo / "CLAUDE.md").write_text("edited\n")
    (repo / ".cursor" / "rules" / "old.mdc").write_text("x\n")

    drift = sync(repo, check=True)

    assert drift == ["CLAUDE.md", ".cursor/rules/old.mdc (stale)"]
    sync(repo, check=False)
    assert not (repo / ".cursor" / "rules" / "old.mdc").exists()


@pytest.mark.parametrize(
    ("text", "message"),
    [
        (SKILL.replace("name: dwh-demo", "name: other"), "must equal the directory name"),
        (SKILL.replace("Use when demonstrating", "Demonstrates"), "must start with 'Use when'"),
        (SKILL.replace("---\n\n#", "version: 2\n---\n\n#", 1), "only name and description"),
        ("# no frontmatter\n", "missing YAML frontmatter"),
    ],
)
def test_invalid_skills_are_rejected(repo, text, message):
    (repo / "skills" / "dwh-demo" / "SKILL.md").write_text(text)

    with pytest.raises(SkillError, match=message):
        load_skills(repo / "skills")


def test_cli_check_exit_codes(repo, capsys):
    assert main(["sync-agents", "--repo", str(repo), "--check"]) == 1
    assert "out of date: CLAUDE.md" in capsys.readouterr().out
    assert main(["sync-agents", "--repo", str(repo)]) == 0
    assert main(["sync-agents", "--repo", str(repo), "--check"]) == 0
    (repo / "AGENTS.md").unlink()
    assert main(["sync-agents", "--repo", str(repo), "--check"]) == 2


def test_malformed_yaml_is_a_skill_error(repo):
    text = SKILL.replace("Use when demonstrating the generator", "Use when a: b")
    (repo / "skills" / "dwh-demo" / "SKILL.md").write_text(text)

    with pytest.raises(SkillError, match="not valid YAML"):
        load_skills(repo / "skills")
    assert main(["sync-agents", "--repo", str(repo), "--check"]) == 2


def test_non_mapping_frontmatter_is_a_skill_error(repo):
    (repo / "skills" / "dwh-demo" / "SKILL.md").write_text("---\n- a\n- b\n---\nBody\n")

    with pytest.raises(SkillError, match="must be a YAML mapping"):
        load_skills(repo / "skills")


def test_hidden_files_in_a_skill_are_ignored(repo):
    (repo / "skills" / "dwh-demo" / ".DS_Store").write_bytes(b"\x00\xff\xfe")
    (repo / "skills" / ".hidden").mkdir()
    (repo / "skills" / "__pycache__").mkdir()
    (repo / "skills" / "dwh-demo" / "__pycache__").mkdir()
    (repo / "skills" / "dwh-demo" / "__pycache__" / "x.pyc").write_bytes(b"\xff\xfe")

    assert set(render(repo)) >= {".claude/skills/dwh-demo/SKILL.md"}
    assert not any(".DS_Store" in name or "pycache" in name for name in render(repo))


def test_hidden_files_in_generated_dirs_are_not_stale(repo):
    sync(repo, check=False)
    junk = repo / ".cursor" / "rules" / ".DS_Store"
    junk.write_bytes(b"\x00\xff")

    assert sync(repo, check=True) == []
    sync(repo, check=False)
    assert junk.exists()


def test_binary_file_in_a_skill_is_a_skill_error(repo):
    (repo / "skills" / "dwh-demo" / "notes.bin").write_bytes(b"\xff\xfe\x00")

    with pytest.raises(SkillError, match="notes.bin"):
        render(repo)


def test_write_reports_removals_and_prunes_empty_directories(repo, capsys):
    sync(repo, check=False)
    stale = repo / ".claude" / "skills" / "gone" / "deep" / "SKILL.md"
    stale.parent.mkdir(parents=True)
    stale.write_text("x\n")
    capsys.readouterr()

    assert main(["sync-agents", "--repo", str(repo)]) == 0

    out = capsys.readouterr().out
    assert "removed .claude/skills/gone/deep/SKILL.md" in out
    assert "(stale)" not in out
    assert not (repo / ".claude" / "skills" / "gone").exists()
    assert (repo / ".claude" / "skills" / "dwh-demo").is_dir()


def test_check_leaves_the_tree_untouched(repo):
    before = sorted(p.relative_to(repo).as_posix() for p in repo.rglob("*"))

    assert sync(repo, check=True) != []

    assert sorted(p.relative_to(repo).as_posix() for p in repo.rglob("*")) == before


def test_generated_files_use_lf_newlines(repo):
    sync(repo, check=False)

    assert b"\r" not in (repo / "CLAUDE.md").read_bytes()
