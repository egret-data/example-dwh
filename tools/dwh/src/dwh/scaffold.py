"""`dwh scaffold`: a model's .sql and .yml (and the SCD4 snapshot) from the warehouse design (spec §6.2)."""

from pathlib import Path, PurePosixPath
from string import Template

import yaml

from dwh.rules.naming import PATTERNS
from dwh.warehouse import Warehouse

HEADER = "# Generated by `dwh scaffold`. Fill every description (DWH-D01/D02) and check each data_type.\n"
AGGREGATE = {"sum": "sum({measure})", "count": "count(*)", "min": "min({measure})", "max": "max({measure})"}
LINE_LENGTH = 110
TODAY = "date '{{ get_dt() }}'"
PARTITION_CONFIG = """{{
  config(
    incremental_strategy='append',
    pre_hook="{% if is_incremental() %}delete from {{ this }} where dt = date '{{ get_dt() }}'{% endif %}",
    properties={"partitioning": "ARRAY['dt']"}
  )
}}
"""

ODS_SQL = Template(
    """{#
  $comment
  Replace the dt partition: delete it first, then append the batch, so re-runs are idempotent.
#}
$config
{% set tz = source_timezone('$source', '$table') %}

select
    -- List and cast every source column; convert timestamps with source_ts('<column>', tz).
$columns    date '{{ get_dt() }}' as dt
from {{ source('$source', '$table') }}
$where"""
)
DIM_SQL = Template(
    """{{ config(materialized='table') }}

-- One current row per natural key (spec D11); the durable key is a hash of the natural key.
select
    {{ dbt_utils.generate_surrogate_key([$natural]) }} as $key,
$columns
from {{ ref('$upstream') }}
-- For a df upstream keep its latest snapshot; adapt the filter for a di upstream.
where dt = (select max(dt) from {{ ref('$upstream') }})
"""
)
DWD_SQL = Template(
    """$config
-- Process $process. Grain: $grain_sentence
${joins}select
$columns
from {{ ref('$upstream') }}
where dt = date '{{ get_dt() }}'
"""
)
DWS_SQL = Template(
    """$config
-- sqlfluff:layout:type:alias_expression:spacing_before:single
-- One statistical period per table ($period); metric columns follow warehouse/metrics.yml.
select
$columns
from {{ ref('$upstream') }}
where dt <= date '{{ get_dt() }}'
group by $group_by
"""
)
ADS_SQL = Template(
    """{{ config(materialized='table') }}

-- Serves one application need: name its consumer in the .yml description (docs/standards/07-dws-ads.md).
select
$columns
from {{ ref('$upstream') }}
"""
)


class ScaffoldError(ValueError):
    """The requested model cannot be scaffolded from the current design."""


def data_type(column: str) -> str:
    if column == "dt" or column.endswith("_date"):
        return "date"
    if column.endswith("_key"):
        return "varchar"
    if column.endswith(("_id", "_cnt", "_dcnt")):
        return "bigint"
    if column.endswith("_amt"):
        return "decimal(18, 2)"
    if column.endswith("_at"):
        return "timestamp(6) with time zone"
    if column.startswith("is_"):
        return "boolean"
    return "varchar"


def metric_type(wh: Warehouse, metric: str) -> str:
    if metric in wh.calculated:
        return "double"
    aggregation = wh.atomic[wh.derived[metric]["atomic"]]["aggregation"]
    return "bigint" if aggregation in ("count", "count_distinct") else "decimal(38, 4)"


def column(name: str, *, contract: bool, tests=(), meta=None, dtype: str | None = None) -> dict:
    col: dict = {"name": name, "description": ""}
    if contract:
        col["data_type"] = dtype or data_type(name)
    if meta:
        col["config"] = {"meta": meta}
    if tests:
        col["data_tests"] = list(tests)
    return col


def relationships(model: str, field: str) -> dict:
    return {"relationships": {"arguments": {"to": f"ref('{model}')", "field": field}}}


def models_yml(name: str, columns: list[dict], *, grain: list[str] | None, contract=False, meta=None) -> str:
    model: dict = {"name": name, "description": ""}
    config: dict = {}
    if contract:
        config["contract"] = {"enforced": True}
    if meta:
        config["meta"] = meta
    if config:
        model["config"] = config
    model["columns"] = columns
    if grain is not None:
        model["data_tests"] = [
            {"dbt_utils.unique_combination_of_columns": {"arguments": {"combination_of_columns": grain}}}
        ]
    return HEADER + yaml.safe_dump({"version": 2, "models": [model]}, sort_keys=False, width=110)


def select_list(items: list[tuple[str, str | None]], *, align: bool = True) -> str:
    """Indented select items; aliases line up on the source text (sqlfluff LT01, as in the ODS models)."""
    width = max((len(expr) for expr, alias in items if alias), default=0) if align else 0
    lines = []
    for index, (expr, alias) in enumerate(items):
        line = f"    {expr.ljust(width)} as {alias}" if alias else f"    {expr}"
        line += "," if index < len(items) - 1 else ""
        if len(line.replace("{{ get_dt() }}", "2026-11-02")) > LINE_LENGTH:
            line += "  -- noqa: LT05"  # a long filter() cannot be split without moving the alias
        lines.append(line)
    return "\n".join(lines)


def dim_model(dimension: dict) -> str:
    return f"dim_{dimension['scope']}_{dimension['name']}"


def key_dimensions(wh: Warehouse) -> dict[str, dict]:
    """`<name>` of a `<name>_key` column -> its dimension: dimension names and bus-matrix role names."""
    found = dict(wh.dimensions)
    for row in wh.bus.values():
        for cell in row["dimensions"]:
            if "role" in cell:
                found[cell["role"]] = wh.dimensions[cell["dimension"]]
    return found


def surrogate(dimension: dict) -> str:
    natural = ", ".join(f"'{k}'" for k in dimension["natural_key"])
    return f"{{{{ dbt_utils.generate_surrogate_key([{natural}]) }}}}"


def _ods(name, parts, wh, grain, metrics, upstream, watermark) -> dict[str, str]:
    source, table, load = parts["source"], parts["table"], parts["load"]
    comment = (
        f"Daily increment of {source}.{table} for the business day dt (spec D12)."
        if load == "di"
        else f"Daily full copy of {source}.{table} into the business day dt (spec D12)."
    )
    sql = ODS_SQL.substitute(
        comment=comment,
        config=PARTITION_CONFIG,
        source=source,
        table=table,
        columns="".join(f"    {g},\n" for g in grain),
        where=f"where {{{{ in_business_day('{watermark}', tz) }}}}\n" if load == "di" else "",
    )
    columns = [column(g, contract=False, tests=["not_null"]) for g in grain]
    columns.append(column("dt", contract=False, tests=["not_null"]))
    folder = f"models/ods/{source}"
    return {
        f"{folder}/{name}.sql": sql,
        f"{folder}/{name}.yml": models_yml(name, columns, grain=[*grain, "dt"]),
    }


def _dim(name, parts, wh, grain, metrics, upstream, watermark) -> dict[str, str]:
    scope, dim_name = parts["scope"], parts["dimension"]
    if parts["hist"]:
        raise ScaffoldError(f"{name}: _hist tables are snapshots; scaffold dim_{scope}_{dim_name} to get one")
    dimension = wh.dimensions.get(dim_name)
    if dimension is None:
        raise ScaffoldError(f"{name}: dimension {dim_name!r} is not in warehouse/dimensions.yml")
    if dimension["scope"] != scope:
        raise ScaffoldError(
            f"{name}: dimension {dim_name} has scope {dimension['scope']}, "
            f"so the model is {dim_model(dimension)}"
        )
    if dimension["history"] == "scd2":
        raise ScaffoldError(f"{name}: scd2 is a documented exception (spec D11); write it by hand")
    if len(upstream) != 1:
        raise ScaffoldError(f"{name}: --from takes exactly one upstream model for a dimension")
    key = f"{dim_name}_key"
    natural = dimension["natural_key"]
    attributes = [a["name"] for a in dimension["attributes"]]
    sql = DIM_SQL.substitute(
        natural=", ".join(f"'{k}'" for k in natural),
        key=key,
        columns=",\n".join(f"    {c}" for c in [*natural, *attributes]),
        upstream=upstream[0],
    )
    columns = [column(key, contract=True, tests=["unique", "not_null"])]
    columns += [column(k, contract=True, tests=["not_null"]) for k in natural]
    columns += [column(a, contract=True) for a in attributes]
    folder = f"models/dim/{scope}"
    files = {
        f"{folder}/{name}.sql": sql,
        f"{folder}/{name}.yml": models_yml(name, columns, grain=None, contract=True),
    }
    if dimension["history"] == "scd4":
        historical = [a["name"] for a in dimension["attributes"] if a["history"] == "historical"]
        if not attributes:
            raise ScaffoldError(f"{name}: an scd4 dimension needs at least one attribute to track")
        snapshot = {
            "snapshots": [
                {
                    "name": f"{name}_hist",
                    "relation": f"ref('{name}')",
                    "description": "",
                    "config": {
                        "unique_key": [key],
                        "strategy": "check",
                        "check_cols": historical or attributes,
                        "snapshot_meta_column_names": {
                            "dbt_valid_from": "valid_from",
                            "dbt_valid_to": "valid_to",
                        },
                    },
                }
            ]
        }
        files[f"snapshots/{name}_hist.yml"] = HEADER + yaml.safe_dump(snapshot, sort_keys=False, width=110)
    return files


def _dwd(name, parts, wh, grain, metrics, upstream, watermark) -> dict[str, str]:
    domain, process_name = parts["domain"], parts["process"]
    process = wh.processes.get(process_name)
    if process is None:
        raise ScaffoldError(f"{name}: process {process_name!r} is not in warehouse/processes.yml")
    if process["domain"] != domain:
        raise ScaffoldError(f"{name}: process {process_name} belongs to domain {process['domain']}")
    row = wh.bus.get(process_name)
    if row is None:
        raise ScaffoldError(f"{name}: add a warehouse/bus_matrix.yml row for process {process_name} first")
    keys = {
        f"{cell.get('role', cell['dimension'])}_key": wh.dimensions[cell["dimension"]]
        for cell in row["dimensions"]
    }
    select = [(g, None) for g in grain if g not in keys]
    select += [(surrogate(dimension), key) for key, dimension in keys.items()]
    select.append((TODAY, "dt"))
    sql = DWD_SQL.substitute(
        config=PARTITION_CONFIG,
        process=process_name,
        grain_sentence=process["grain"],
        joins="".join(f"-- joins {{{{ ref('{model}') }}}}\n" for model in upstream[1:]),
        columns=select_list(select),
        upstream=upstream[0],
    )
    columns = []
    for g in grain:
        tests = ["not_null"]
        if g in keys:
            tests.append(relationships(dim_model(keys[g]), f"{keys[g]['name']}_key"))
        columns.append(column(g, contract=True, tests=tests))
    for key, dimension in keys.items():
        if key not in grain:
            columns.append(
                column(
                    key,
                    contract=True,
                    tests=[relationships(dim_model(dimension), f"{dimension['name']}_key")],
                )
            )
    columns.append(column("dt", contract=True, tests=["not_null"]))
    folder = f"models/dwd/{domain}"
    return {
        f"{folder}/{name}.sql": sql,
        f"{folder}/{name}.yml": models_yml(
            name, columns, grain=[*grain, "dt"], contract=True, meta={"process": process_name}
        ),
    }


def period_condition(derived: dict, period: str) -> str | None:
    if period == "1d":
        return f"dt = {TODAY}"
    if period == "1w":
        return f"dt > {TODAY} - interval '7' day"
    if period == "nd":
        return f"dt > {TODAY} - interval '{derived['days']}' day"
    return None  # td: all history up to dt


def _dws(name, parts, wh, grain, metrics, upstream, watermark) -> dict[str, str]:
    domain, period = parts["domain"], parts["period"]
    if domain not in wh.domains:
        raise ScaffoldError(f"{name}: {domain!r} is not a domain in warehouse/domains.yml")
    if period in ("hh", "mm"):
        raise ScaffoldError(f"{name}: scaffold supports 1d, nd, td and 1w DWS tables")
    if not metrics:
        raise ScaffoldError(f"{name}: --metric is required for a DWS table")
    dims = key_dimensions(wh)
    select = [(g, None) for g in grain]
    metric_columns = []
    for metric in metrics:
        derived = wh.derived.get(metric)
        if derived is None:
            raise ScaffoldError(f"{metric}: is not a derived metric in warehouse/metrics.yml")
        if derived["period"] != period:
            raise ScaffoldError(
                f"{metric}: period {derived['period']} does not match the table period {period}"
            )
        atomic = wh.atomic[derived["atomic"]]
        if atomic["aggregation"] not in AGGREGATE:
            raise ScaffoldError(f"{metric}: {atomic['aggregation']} metrics are not stored in DWS (DWH-M02)")
        expression = AGGREGATE[atomic["aggregation"]].format(measure=atomic["name"])
        conditions = [wh.modifiers[m]["predicate"] for m in derived.get("modifiers", [])]
        window = period_condition(derived, period)
        if window:
            conditions.append(window)
        if conditions:
            expression += f" filter (where {' and '.join(conditions)})"
        select.append((expression, metric))
        metric_columns.append(
            column(metric, contract=True, meta={"metric": metric}, dtype=metric_type(wh, metric))
        )
    sql = DWS_SQL.substitute(
        config=PARTITION_CONFIG,
        period=period,
        columns=select_list([*select, (TODAY, "dt")], align=False),
        upstream=upstream[0],
        group_by=", ".join(grain),
    )
    columns = []
    for g in grain:
        tests: list = ["not_null"]
        stem = g.removesuffix("_key")
        if g.endswith("_key"):
            if stem not in dims:
                raise ScaffoldError(f"{name}: grain key {g} does not name a dimension or bus-matrix role")
            tests.append(relationships(dim_model(dims[stem]), f"{dims[stem]['name']}_key"))
        columns.append(column(g, contract=True, tests=tests))
    columns += metric_columns
    columns.append(column("dt", contract=True, tests=["not_null"]))
    folder = f"models/dws/{domain}"
    return {
        f"{folder}/{name}.sql": sql,
        f"{folder}/{name}.yml": models_yml(
            name, columns, grain=[*grain, "dt"], contract=True, meta={"grain": grain}
        ),
    }


def _ads(name, parts, wh, grain, metrics, upstream, watermark) -> dict[str, str]:
    if not metrics:
        raise ScaffoldError(f"{name}: --metric is required for an ADS table")
    select = [(g, None) for g in grain]
    for metric in metrics:
        if metric in wh.derived:
            select.append((metric, None))
        elif metric in wh.calculated:
            select.append((wh.calculated[metric]["formula"], metric))
        else:
            raise ScaffoldError(f"{metric}: is not a derived or calculated metric in warehouse/metrics.yml")
    sql = ADS_SQL.substitute(columns=select_list([*select, ("dt", None)]), upstream=upstream[0])
    columns = [column(g, contract=False, tests=["not_null"]) for g in grain]
    columns += [column(m, contract=False, meta={"metric": m}) for m in metrics]
    columns.append(column("dt", contract=False, tests=["not_null"]))
    folder = f"models/ads/{parts['app']}"
    return {
        f"{folder}/{name}.sql": sql,
        f"{folder}/{name}.yml": models_yml(name, columns, grain=[*grain, "dt"]),
    }


BUILDERS = {"ods": _ods, "dim": _dim, "dwd": _dwd, "dws": _dws, "ads": _ads}


def scaffold(
    name: str,
    wh: Warehouse,
    *,
    project_dir: str = "dags/dbt",
    grain=(),
    metrics=(),
    upstream=(),
    watermark: str = "updated_at",
) -> dict[str, str]:
    layer = name.split("_", 1)[0]
    pattern = PATTERNS.get(layer)
    if pattern is None:
        raise ScaffoldError(f"{name}: the name must start with ods_, dim_, dwd_, dws_ or ads_")
    match = pattern.match(name)
    if match is None:
        raise ScaffoldError(
            f"{name}: does not follow the {layer} naming template (docs/standards/02-naming.md)"
        )
    if layer != "dim" and not grain:
        raise ScaffoldError(f"{name}: --grain is required (the columns that, with dt, identify one row)")
    if layer != "ods" and not upstream:
        raise ScaffoldError(f"{name}: --from is required (the upstream model or models)")
    files = BUILDERS[layer](
        name, match.groupdict(), wh, list(grain), list(metrics), list(upstream), watermark
    )
    return {
        (str(PurePosixPath(project_dir, path)) if project_dir else path): text for path, text in files.items()
    }


def write_files(files: dict[str, str], repo: Path) -> list[str]:
    existing = [path for path in files if (repo / path).exists()]
    if existing:
        raise ScaffoldError(f"refusing to overwrite {', '.join(existing)}")
    for path, text in files.items():
        target = repo / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
    return list(files)
